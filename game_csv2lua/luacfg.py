def LUA_MODULE_MULTIPLE_FUNC(name, data, defElems):
	N = 10000
	data2 = data[N:]
	data2holder = ['%s= 0' % x.split('=')[0] for x in data2]
	src1 = '''%s = {
%s,
	__size = %d,
	__default = {
		__index = {
			%s
		}
	}
}
''' % (name, ',\r\n'.join(data[:N] + data2holder), len(data), ',\r\n\t\t\t'.join(defElems))

	src2 = '''
(function()
	local csv = %s
%s
end)()
''' % (name, '\r\n'.join(['\tcsv%s' % x.lstrip('\t') for x in data2]))

	return src1 + src2

