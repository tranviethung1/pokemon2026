def load_bracket_map() -> dict[str, str]:
    m: dict[str, str] = {}
    with open(KEY_WORDS, newline="", encoding="utf-8") as f:
        r = csv.reader(f)
        rows = list(r)
    for row in rows[3:]:
        if len(row) < 4:
            continue
        name, _desc, key = row[1], row[2], row[3]
        if key.startswith("【") and name.startswith("【"):
            m[key.strip()] = name.strip()
    return m


def load_pokemon_cn_en() -> dict[str, str]:
    out: dict[str, str] = {}
    text = DICT_MD.read_text(encoding="utf-8")
    for line in text.splitlines():
        if not line.strip().startswith("|"):
            continue
        parts = [p.strip() for p in line.split("|")]
        if len(parts) < 5:
            continue
        try:
            int(parts[1])
        except ValueError:
            continue
        cn, en = parts[2], parts[3]
        if cn and en and not cn.startswith(":"):
            out[cn] = en
    return out


