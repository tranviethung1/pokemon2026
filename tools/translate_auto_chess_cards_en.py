def apply_brackets(s: str, bm: dict[str, str]) -> str:
    for cn, en in sorted(bm.items(), key=lambda x: -len(x[0])):
        s = s.replace(cn, en)
    return s


def apply_phrases(s: str) -> str:
    for cn, en in PHRASES:
        s = s.replace(cn, en)
    return s


def translate_name(name: str, names: dict[str, str]) -> str:
    if not name:
        return name
    inner = name
    if name.startswith("|") and name.endswith("|"):
        inner = name[1:-1]
    if inner in EXTRA_NAMES:
        en = EXTRA_NAMES[inner]
    else:
        en = names.get(inner, inner)
    if name.startswith("|") and name.endswith("|"):
        return f"|{en}|"
    return en


def translate_field(s: str, bm: dict[str, str]) -> str:
    if not s or not CJK_RE.search(s):
        return s
    s = apply_brackets(s, bm)
    s = apply_phrases(s)
    s = re.sub(r"  +", " ", s)
    return s


